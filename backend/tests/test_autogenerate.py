import shutil
from pathlib import Path

import pytest
from alembic.config import Config
from sqlalchemy import Column, Integer, MetaData, Table

from alembic import command
from app.storage.migrate import ALEMBIC_INI, run_migrations
from app.storage.models import Base, UtcDateTime


@pytest.fixture
def autogenerate_config(tmp_path: Path) -> Config:
    """An alembic config whose versions directory is a scratch copy."""
    script_location = tmp_path / "alembic"
    shutil.copytree(ALEMBIC_INI.parent / "alembic", script_location)
    config = Config(str(ALEMBIC_INI))
    config.attributes["configure_logger"] = False
    config.set_main_option("script_location", str(script_location))
    url = f"sqlite:///{tmp_path / 'autogen.db'}"
    run_migrations(url)
    config.set_main_option("sqlalchemy.url", url)
    return config


def _revision_text(config: Config, message: str) -> str:
    script = command.revision(config, message=message, autogenerate=True)
    return Path(script.path).read_text(encoding="utf-8")


def test_autogenerated_migration_renders_our_datetime_type_with_its_import(
    autogenerate_config: Config,
):
    Table(
        "reminders",
        Base.metadata,
        Column("id", Integer, primary_key=True),
        Column("due_at", UtcDateTime(), nullable=False),
    )
    try:
        text = _revision_text(autogenerate_config, "add reminders")
    finally:
        Base.metadata.remove(Base.metadata.tables["reminders"])

    assert "from app.storage.models import UtcDateTime" in text
    assert "UtcDateTime()" in text
    assert "app.storage.models.UtcDateTime" not in text


def test_autogenerating_against_the_current_models_writes_an_empty_migration(
    autogenerate_config: Config,
):
    text = _revision_text(autogenerate_config, "no change")
    assert "op." not in text


def test_metadata_is_unchanged_by_the_autogenerate_tests():
    assert "reminders" not in Base.metadata.tables
    assert MetaData is not None
